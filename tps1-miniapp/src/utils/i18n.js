export const useTranslation = () => {
  const language = useAppStore(state => state.language) || 'vi';
  
  const t = (key, params = {}) => {
    let text = dictionary[language][key];
    if (!text) {
      // Fallback to vi
      text = dictionary['vi'][key] || key;
    }
    
    // Replace params e.g. {{count}}
    Object.keys(params).forEach(p => {
      text = text.replace(new RegExp(`{{${p}}}`, 'g'), params[p]);
    });
    
    return text;
  };
  
  return { t, language };
};
